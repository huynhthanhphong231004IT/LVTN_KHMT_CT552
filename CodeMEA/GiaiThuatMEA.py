def table_get(table: np.ndarray, val: int) -> int:
    if val is None:
        return None
    val = int(val) & 0xFF
    hi = (val >> 4) & 0xF
    lo = val & 0xF
    return int(table[hi][lo])

def pad_pkcs7(data: bytes, block_size: int = 9) -> bytes:
    pad_len = block_size - (len(data) % block_size)
    return data + bytes([pad_len] * pad_len)

def unpad_pkcs7(data: bytes) -> bytes:
    if not data:
        return data
    pad_len = data[-1]
    if pad_len < 1 or pad_len > len(data):
        return data 
    return data[:-pad_len]

def pad_bytes(b: bytes, block_size: int = 9) -> bytes:
    return pad_pkcs7(b, block_size)

def text_to_blocks_hex_pairs(text: str):
    data = pad_pkcs7(text.encode('utf-8'), block_size=9)
    chunks = [data[i:i+9] for i in range(0, len(data), 9)]
    
    # print(chunks)
    blocks = [np.frombuffer(chunk, dtype=np.uint8).reshape((3,3), order='F') for chunk in chunks]
    return blocks

def blocks_hex_pairs_to_text(blocks: List[np.ndarray]) -> str:
    data = bytearray()
    for blk in blocks:
        data.extend(bytes(blk.flatten(order='F')))
    return unpad_pkcs7(data).decode('utf-8', errors='ignore')

def xor_with_key(block: np.ndarray, key: np.ndarray) -> np.ndarray:
    block_arr = np.array([[int(x,16) if isinstance(x,str) else x for x in row] for row in block], dtype=np.uint16)
    key_arr   = np.array([[int(x,16) if isinstance(x,str) else x for x in row] for row in key], dtype=np.uint16)
    return np.bitwise_xor(block_arr, key_arr)

def apply_table_to_block(block, table):
    block = np.array(block, dtype=np.uint8)  # đảm bảo là numpy
    table = np.array(table, dtype=np.uint8)  # đảm bảo là numpy
    out = np.zeros_like(block, dtype=np.uint8)

    for r in range(block.shape[0]):
        for c in range(block.shape[1]):
            val = int(block[r, c])
            if val != 0:
                out[r, c] = table_get(table, val)
            else:
                out[r, c] = 0   # log(0) = 0 để tránh lỗi
    return out

def shift_rows(block: np.ndarray) -> np.ndarray:
    out = np.zeros_like(block, dtype=np.uint8)
    for r in range(3):
        out[r] = np.roll(block[r], -r) 
    return out

def inv_shift_rows(block: np.ndarray) -> np.ndarray:
    out = np.zeros_like(block, dtype=np.uint8)
    for r in range(3):
        out[r] = np.roll(block[r], r)  
    return out

def cycle_rows(block: np.ndarray) -> np.ndarray:
    out = block.copy()
    out[1] = block[0]
    out[2] = block[1]
    out[0] = block[2]
    return out

def inv_cycle_rows(block: np.ndarray) -> np.ndarray:
    out = block.copy()
    out[0] = block[1]
    out[1] = block[2]
    out[2] = block[0]
    return out

