    # print(blocks)
    # Tạo danh sách keys (6 ma trận)
    keys = []
    for key_hex_matrix in key_hex_list:
        key = np.zeros((3, 3), dtype=np.uint8)
        for r in range(3):
            for c in range(3):
                key[r, c] = int(key_hex_matrix[r][c], 16) & 0xFF
